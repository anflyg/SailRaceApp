// Exercises the real UI and local logger with a fake clock and synthetic GPS.
import assert from 'node:assert/strict'
import { createServer } from 'vite'
import { chromium } from 'playwright'

const server = await createServer({ server: { host: '127.0.0.1', port: 5189, strictPort: true } })
let browser
try {
  await server.listen()
  browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await context.addInitScript(() => {
    const initial = Date.now()
    const position = () => ({ timestamp: Date.now(), coords: {
      latitude: (Date.now() - initial) / 1000 * 3 / 111320, longitude: 0,
      accuracy: 2, speed: 3, heading: 0, altitude: null, altitudeAccuracy: null,
    } })
    Object.defineProperty(navigator, 'geolocation', { value: {
      getCurrentPosition: success => success(position()),
      watchPosition: success => { success(position()); return setInterval(() => success(position()), 1000) },
      clearWatch: id => clearInterval(id),
    } })
  })
  const page = await context.newPage()
  page.setDefaultTimeout(8000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.clock.install({ time: new Date('2026-01-01T12:00:00Z') })
  await page.goto('http://127.0.0.1:5189/')
  await page.clock.runFor(2000)
  await page.locator('.aster-race-splash').waitFor({ state: 'detached' })
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  const timer = page.locator('.timer-display')
  const start = () => timer.click()
  const choose = minutes => page.locator('.duration-button').filter({ hasText: String(minutes) }).click()
  const advance = seconds => page.clock.runFor(seconds * 1000)
  const stopButton = page.locator('.recording-stop-button')
  const dialog = page.getByRole('dialog', { name: 'Avsluta race' })
  const openEndRace = async () => { await stopButton.click(); await dialog.waitFor({ state: 'visible' }) }
  const cancelEndRace = () => dialog.getByRole('button', { name: 'Avbryt' }).click()
  const confirmEndRace = () => dialog.getByRole('button', { name: 'Avsluta race' }).click()
  const recordingStatus = page.getByRole('status').filter({ hasText: 'Inspelning pågår' })
  assert.equal(await stopButton.count(), 0, 'stopped Start timer hides recording control')
  assert.equal(await recordingStatus.count(), 0, 'Start never shows recording status')
  const snapshot = () => page.evaluate(() => ({
    logger: JSON.parse(localStorage.getItem('aster-race:race-logger:v1')),
    races: JSON.parse(localStorage.getItem('aster-race:race-storage:v1')).racesById,
  }))

  await start()
  assert.equal(await stopButton.count(), 1, 'running countdown shows stop control')
  assert.equal(await recordingStatus.count(), 0, 'running Start shows no recording status')
  await advance(10)
  assert.equal(await timer.innerText(), '4:50')
  await openEndRace()
  assert.equal(await dialog.evaluate(element => element.matches(':modal')), true)
  assert.equal(await dialog.getByRole('button', { name: 'Avbryt' }).evaluate(element => document.activeElement === element), true)
  await page.keyboard.press('Tab')
  assert.equal(await dialog.getByRole('button', { name: 'Avsluta race' }).evaluate(element => document.activeElement === element), true)
  await timer.evaluate(element => element.focus())
  assert.equal(await dialog.evaluate(element => element.contains(document.activeElement)), true, 'background cannot take focus')
  await page.keyboard.press('Escape')
  assert.equal(await dialog.count(), 0, 'Escape cancels without ending the race')
  await openEndRace()
  const duringDialog = await snapshot()
  await advance(10)
  assert.equal(await timer.innerText(), '4:40', 'countdown continues with dialog open')
  let afterDialog = await snapshot()
  assert.equal(afterDialog.logger.activeRaceId, duringDialog.logger.activeRaceId)
  assert.equal(afterDialog.logger.countdownRevision, duringDialog.logger.countdownRevision)
  assert.equal(afterDialog.logger.scheduledStartTime, duringDialog.logger.scheduledStartTime)
  assert.ok(afterDialog.races[duringDialog.logger.activeRaceId].samples.length > duringDialog.races[duringDialog.logger.activeRaceId].samples.length)
  await cancelEndRace()
  assert.equal(await dialog.count(), 0)
  await start()
  await choose(5)
  await start()
  await advance(14)
  await start()
  assert.equal(await timer.innerText(), '4:46')
  assert.equal(await stopButton.count(), 0, 'paused countdown hides stop control')
  let state = await snapshot()
  const race1 = state.logger.activeRaceId
  const token1 = state.logger.countdownRevision
  assert.equal(state.logger.scheduledStartTime, undefined)
  const sampleCount = state.races[race1].samples.length
  assert.ok(sampleCount > 0)

  await start()
  assert.equal(await stopButton.count(), 1, 'resumed countdown shows stop control again')
  assert.equal(await recordingStatus.count(), 0, 'resumed Start still shows no recording status')
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, race1)
  assert.ok(state.logger.countdownRevision > token1)
  await advance(5)
  await start()
  assert.equal(await stopButton.count(), 0, 'pausing again hides the stop control')
  assert.equal(await timer.innerText(), '4:41')
  await choose(4)
  assert.equal(await timer.innerText(), '4:00')
  await start()
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, race1)
  assert.ok(state.races[race1].samples.length >= sampleCount)
  assert.equal(await page.locator('.countdown-blocked-status').count(), 0)
  await advance(2)
  await start()
  await choose(3)
  await start()
  assert.equal((await snapshot()).logger.activeRaceId, race1)
  await advance(2)
  await start()
  await choose(1)
  await start()
  await advance(60)
  state = await snapshot()
  assert.ok(state.races[race1].startGunTime)
  const gun1 = state.races[race1].startGunTime
  await start()
  await start()
  await advance(2)
  await start()
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, race1)
  assert.equal(state.races[race1].startGunTime, gun1)
  await choose(1)
  await start()
  state = await snapshot()
  const race2 = state.logger.activeRaceId
  assert.notEqual(race2, race1)
  assert.ok(state.races[race1].endTime)
  assert.equal(Object.keys(state.races).length, 2)

  await timer.dispatchEvent('pointerdown')
  await page.clock.runFor(600)
  await timer.dispatchEvent('pointerup')
  await timer.dispatchEvent('click')
  state = await snapshot()
  assert.equal(await timer.innerText(), '1:00')
  assert.equal(state.logger.activeRaceId, race2)
  assert.equal(state.logger.scheduledStartTime, undefined)
  assert.equal(state.races[race2].endTime, undefined)
  await start()
  assert.equal((await snapshot()).logger.activeRaceId, race2)
  await advance(2)
  await start()
  assert.equal(await stopButton.count(), 0, 'paused countdown hides stop action')
  await start()
  assert.equal(await stopButton.count(), 1, 'resuming countdown restores stop action')
  assert.equal(await stopButton.innerText(), 'Avsluta race')
  const beforeCancel = await snapshot()
  const timeBeforeCancel = await timer.innerText()
  await openEndRace()
  await cancelEndRace()
  assert.deepEqual((await snapshot()).logger, beforeCancel.logger, 'cancel leaves the active countdown token unchanged')
  assert.equal(await timer.innerText(), timeBeforeCancel)
  await advance(1)
  assert.notEqual(await timer.innerText(), timeBeforeCancel, 'timer continues after cancellation')
  const samplesBeforeStop = (await snapshot()).races[race2].samples.length
  await openEndRace()
  await confirmEndRace()
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, null)
  assert.ok(state.races[race2].endTime)
  assert.equal(state.races[race2].startGunTime, undefined)
  assert.equal(state.races[race2].samples.length, samplesBeforeStop)
  assert.equal(await timer.innerText(), '1:00', 'ending a race resets the selected countdown')
  assert.equal(await stopButton.count(), 0)
  await advance(65)
  assert.equal(await timer.innerText(), '1:00', 'ended timer remains stopped')
  assert.equal((await snapshot()).races[race2].startGunTime, undefined, 'ended pre-start never gets a delayed gun')
  await start()
  state = await snapshot()
  const race3 = state.logger.activeRaceId
  assert.ok(race3)
  assert.notEqual(race3, race2)
  assert.equal(Object.keys(state.races).length, 3)
  await advance(6)
  await start()
  assert.equal(await stopButton.count(), 0, 'pausing hides the Start control while recording remains active')
  await page.getByRole('button', { name: 'Analys', exact: true }).click()
  assert.equal(await page.locator('.recording-stop-button').count(), 1, 'Analysis keeps stop control while timer is paused')
  assert.equal(await page.getByRole('status').filter({ hasText: 'Inspelning pågår' }).count(), 1, 'Analysis keeps recording status')
  await openEndRace()
  await confirmEndRace()
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, null)
  assert.ok(state.races[race3].endTime)
  assert.equal(state.races[race3].startGunTime, undefined)
  assert.ok(state.races[race3].samples.length > 0)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  assert.equal(await timer.innerText(), '1:00', 'ending from Analysis resets Start to the selected minutes')
  await start()
  state = await snapshot()
  const race4 = state.logger.activeRaceId
  assert.ok(race4)
  assert.notEqual(race4, race3)
  await advance(58)
  await openEndRace()
  await advance(3)
  state = await snapshot()
  const gun4 = state.races[race4].startGunTime
  assert.ok(gun4)
  await advance(10)
  assert.equal((await snapshot()).races[race4].startGunTime, gun4, 'gun is registered only once while dialog is open')
  assert.equal(await dialog.isVisible(), true, 'dialog survives automatic view change')
  await confirmEndRace()
  state = await snapshot()
  assert.equal(state.logger.activeRaceId, null)
  assert.equal(state.races[race4].startGunTime, gun4, 'ending after the gun preserves its time')
  assert.ok(state.races[race4].endTime)
  await page.getByRole('button', { name: 'Start', exact: true }).click()
  assert.equal(await timer.innerText(), '1:00')
  await start()
  const race5 = (await snapshot()).logger.activeRaceId
  assert.ok(race5)
  assert.notEqual(race5, race4, 'starting after ending creates a new race')
  assert.deepEqual(errors, [])
  console.log('Start resynchronization UI: PASS (synthetic GPS; no external requests)')
  await context.close()
} finally {
  await browser?.close()
  await server.close()
}
